def test_split_is_deterministic_for_a_seed():
    a = split_train_holdout(40, holdout_frac=0.25, seed=7)
    b = split_train_holdout(40, holdout_frac=0.25, seed=7)
    c = split_train_holdout(40, holdout_frac=0.25, seed=8)

    assert a == b
    assert a != c


def test_split_partitions_all_views_without_overlap():
    train, hold = split_train_holdout(40, holdout_frac=0.25, seed=0)

    assert len(hold) == 10
    assert len(train) == 30
    assert set(train).isdisjoint(hold)
    assert set(train) | set(hold) == set(range(40))


def test_split_yields_no_holdout_when_views_are_scarce():
    train, hold = split_train_holdout(13, holdout_frac=0.25, seed=0, min_train=12)

    assert len(hold) <= 1
    assert len(train) >= 12
